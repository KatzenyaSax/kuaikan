-- 评论里的 @ 提及。
--
-- 为什么要落库而不只放进事件：
--   消息事件只需要"通知谁"，而**读评论的人需要知道哪几个 @ 是可点的**。
--   正文是纯文本（`@林间 你看这个`），前端据此渲染成蓝色链接，
--   但"林间"到底对应哪个 userId、是不是真的解析成功过，只有写入时知道。
--   不落库就得让每个读者重新解析一遍，还会因为后来的改名/退社得出不同结论。
--
-- 为什么存昵称快照而不只存 id：
--   正文里是**当时的昵称**。对方改名后，用当前昵称去正文里匹配就匹配不上了，
--   `@旧名` 会退化成一串死文字。存下当时解析出的 {id, nickname} 才能稳定渲染。
--   这与"消息是历史快照"是同一个道理（不变量 9）。
--
-- 格式：JSON 数组，元素 {"id":"<雪花id>","nickname":"<当时昵称>"}
--   id 用字符串，与全站 Long→String 的序列化规则保持一致。
--   长度上限 1000 字节：正常评论里 @ 两三个人，绰绰有余。
--
-- 这个文件是 P4.1 建的。它与评论写入在同一条路径上，必须一起上线。

ALTER TABLE t_comment
  ADD COLUMN mentions JSON NULL COMMENT '解析成功并被 @ 的用户快照 [{id,nickname}]，未解析为 NULL';
